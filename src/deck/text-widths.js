const FALLBACK = [0.6, 0.7];

function charEm(ch, bold) {
  const m = CHAR_W[ch];
  return m ? m[bold ? 1 : 0] : FALLBACK[bold ? 1 : 0];
}
// ширина строки в единицах кегля (пробелы учитываются)
function lineWidth(line, bold) {
  let w = 0;
  for (const ch of line) w += charEm(ch, bold);
  return w;
}
// ширина самой длинной неразрывной части строки в единицах кегля
function widestTokenEm(text, bold) {
  let m = 0;
  for (const para of String(text).split('\n')) {
    for (const word of para.split(/\s+/)) {
      const e = lineWidth(word, bold);
      if (e > m) m = e;
    }
  }
  return m;
}
// ширина текста в pt при заданном кегле
function textWidth(text, size, { bold = false, mono = false } = {}) {
  if (mono) {
    const longest = Math.max(1, ...String(text).split('\n').map(l => l.length));
    return longest * size * 0.6;
  }
  let em = 0;
  for (const para of String(text).split('\n')) {
    const e = lineWidth(para, bold);
    if (e > em) em = e;
  }
  return em * size;
}

